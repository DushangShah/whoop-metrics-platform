-- Raw tables for the PMData CSV files.
-- Raw layer = original values kept as text, plus where each row came from.
-- Safe to re-run: CREATE OR REPLACE rebuilds the table, COPY INTO reloads from the stage.
USE ROLE TRANSFORMER;
USE WAREHOUSE DEV_WH;
USE SCHEMA WHOOP_METRICS.RAW;

CREATE OR REPLACE TABLE RAW_SLEEP_SCORE (
  TIMESTAMP_RAW STRING,
  SLEEP_LOG_ENTRY_ID STRING,
  OVERALL_SCORE STRING,
  COMPOSITION_SCORE STRING,
  REVITALIZATION_SCORE STRING,
  DURATION_SCORE STRING,
  DEEP_SLEEP_IN_MINUTES STRING,
  RESTING_HEART_RATE STRING,
  RESTLESSNESS STRING,
  SOURCE_FILE STRING,
  PARTICIPANT_ID STRING,
  LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

CREATE OR REPLACE TABLE RAW_WELLNESS (
  EFFECTIVE_TIME_FRAME STRING,
  FATIGUE STRING,
  MOOD STRING,
  READINESS STRING,
  SLEEP_DURATION_H STRING,
  SLEEP_QUALITY STRING,
  SORENESS STRING,
  SORENESS_AREA STRING,
  STRESS STRING,
  SOURCE_FILE STRING,
  PARTICIPANT_ID STRING,
  LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

COPY INTO RAW_SLEEP_SCORE (
  TIMESTAMP_RAW, SLEEP_LOG_ENTRY_ID, OVERALL_SCORE, COMPOSITION_SCORE, REVITALIZATION_SCORE,
  DURATION_SCORE, DEEP_SLEEP_IN_MINUTES, RESTING_HEART_RATE, RESTLESSNESS,
  SOURCE_FILE, PARTICIPANT_ID)
FROM (
  SELECT $1, $2, $3, $4, $5, $6, $7, $8, $9,
         METADATA$FILENAME, SPLIT_PART(METADATA$FILENAME, '/', 2)
  FROM @PMDATA_STAGE/sleep_score/
)
FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT);

COPY INTO RAW_WELLNESS (
  EFFECTIVE_TIME_FRAME, FATIGUE, MOOD, READINESS, SLEEP_DURATION_H, SLEEP_QUALITY,
  SORENESS, SORENESS_AREA, STRESS, SOURCE_FILE, PARTICIPANT_ID)
FROM (
  SELECT $1, $2, $3, $4, $5, $6, $7, $8, $9,
         METADATA$FILENAME, SPLIT_PART(METADATA$FILENAME, '/', 2)
  FROM @PMDATA_STAGE/wellness/
)
FILE_FORMAT = (FORMAT_NAME = CSV_FORMAT);

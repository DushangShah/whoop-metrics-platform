-- Raw table for sleep records produced by spark_jobs/sleep_logs.py.
-- One row per record in the file, including repeated logIds. dbt resolves duplicates.
-- Safe to re-run: CREATE OR REPLACE rebuilds the table and resets load history.
USE ROLE TRANSFORMER;
USE WAREHOUSE DEV_WH;
USE SCHEMA WHOOP_METRICS.RAW;

CREATE FILE FORMAT IF NOT EXISTS PARQUET_FORMAT TYPE = PARQUET;

CREATE OR REPLACE TABLE RAW_SLEEP_LOGS (
  PARTICIPANT_ID STRING,
  LOG_ID STRING,
  DATE_OF_SLEEP STRING,
  START_TIME_RAW STRING,
  END_TIME_RAW STRING,
  DURATION_MS FLOAT,
  MINUTES_TO_FALL_ASLEEP FLOAT,
  MINUTES_ASLEEP FLOAT,
  MINUTES_AWAKE FLOAT,
  MINUTES_AFTER_WAKEUP FLOAT,
  TIME_IN_BED FLOAT,
  EFFICIENCY FLOAT,
  SLEEP_TYPE STRING,
  INFO_CODE FLOAT,
  MAIN_SLEEP BOOLEAN,
  DEEP_COUNT FLOAT,
  DEEP_MINUTES FLOAT,
  DEEP_30D_AVG FLOAT,
  LIGHT_COUNT FLOAT,
  LIGHT_MINUTES FLOAT,
  LIGHT_30D_AVG FLOAT,
  REM_COUNT FLOAT,
  REM_MINUTES FLOAT,
  REM_30D_AVG FLOAT,
  WAKE_COUNT FLOAT,
  WAKE_MINUTES FLOAT,
  WAKE_30D_AVG FLOAT,
  ASLEEP_COUNT FLOAT,
  ASLEEP_MINUTES FLOAT,
  RESTLESS_COUNT FLOAT,
  RESTLESS_MINUTES FLOAT,
  AWAKE_COUNT FLOAT,
  AWAKE_MINUTES FLOAT,
  LEVELS_SUMMARY_JSON STRING,
  SOURCE_FILE STRING,
  LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

COPY INTO RAW_SLEEP_LOGS (
  PARTICIPANT_ID, LOG_ID, DATE_OF_SLEEP, START_TIME_RAW, END_TIME_RAW, DURATION_MS,
  MINUTES_TO_FALL_ASLEEP, MINUTES_ASLEEP, MINUTES_AWAKE, MINUTES_AFTER_WAKEUP, TIME_IN_BED,
  EFFICIENCY, SLEEP_TYPE, INFO_CODE, MAIN_SLEEP,
  DEEP_COUNT, DEEP_MINUTES, DEEP_30D_AVG, LIGHT_COUNT, LIGHT_MINUTES, LIGHT_30D_AVG,
  REM_COUNT, REM_MINUTES, REM_30D_AVG, WAKE_COUNT, WAKE_MINUTES, WAKE_30D_AVG,
  ASLEEP_COUNT, ASLEEP_MINUTES, RESTLESS_COUNT, RESTLESS_MINUTES, AWAKE_COUNT, AWAKE_MINUTES,
  LEVELS_SUMMARY_JSON, SOURCE_FILE)
FROM (
  SELECT
    $1:participant_id::STRING, $1:log_id::STRING, $1:date_of_sleep::STRING,
    $1:start_time_raw::STRING, $1:end_time_raw::STRING, $1:duration_ms::FLOAT,
    $1:minutes_to_fall_asleep::FLOAT, $1:minutes_asleep::FLOAT, $1:minutes_awake::FLOAT,
    $1:minutes_after_wakeup::FLOAT, $1:time_in_bed::FLOAT,
    $1:efficiency::FLOAT, $1:sleep_type::STRING, $1:info_code::FLOAT, $1:main_sleep::BOOLEAN,
    $1:deep_count::FLOAT, $1:deep_minutes::FLOAT, $1:deep_30d_avg::FLOAT,
    $1:light_count::FLOAT, $1:light_minutes::FLOAT, $1:light_30d_avg::FLOAT,
    $1:rem_count::FLOAT, $1:rem_minutes::FLOAT, $1:rem_30d_avg::FLOAT,
    $1:wake_count::FLOAT, $1:wake_minutes::FLOAT, $1:wake_30d_avg::FLOAT,
    $1:asleep_count::FLOAT, $1:asleep_minutes::FLOAT,
    $1:restless_count::FLOAT, $1:restless_minutes::FLOAT,
    $1:awake_count::FLOAT, $1:awake_minutes::FLOAT,
    $1:levels_summary_json::STRING, $1:source_file::STRING
  FROM @PMDATA_STAGE/sleep_logs/
)
FILE_FORMAT = (FORMAT_NAME = PARQUET_FORMAT);

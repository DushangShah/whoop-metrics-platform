-- Raw table for zone minutes produced by spark_jobs/zone_minutes.py.
-- Safe to re-run: CREATE OR REPLACE rebuilds the table and resets load history.
USE ROLE TRANSFORMER;
USE WAREHOUSE DEV_WH;
USE SCHEMA WHOOP_METRICS.RAW;

CREATE FILE FORMAT IF NOT EXISTS PARQUET_FORMAT TYPE = PARQUET;

CREATE OR REPLACE TABLE RAW_ZONE_MINUTES (
  PARTICIPANT_ID STRING,
  ZONE_DATE STRING,
  MINUTES_BELOW_ZONE_1 FLOAT,
  MINUTES_ZONE_1 FLOAT,
  MINUTES_ZONE_2 FLOAT,
  MINUTES_ZONE_3 FLOAT,
  ANY_ZONE_MISSING BOOLEAN,
  TOTAL_MINUTES FLOAT,
  SOURCE_FILE STRING,
  LOADED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP()
);

COPY INTO RAW_ZONE_MINUTES (
  PARTICIPANT_ID, ZONE_DATE, MINUTES_BELOW_ZONE_1, MINUTES_ZONE_1, MINUTES_ZONE_2,
  MINUTES_ZONE_3, ANY_ZONE_MISSING, TOTAL_MINUTES, SOURCE_FILE)
FROM (
  SELECT
    $1:participant_id::STRING,
    $1:zone_date::STRING,
    $1:minutes_below_zone_1::FLOAT,
    $1:minutes_zone_1::FLOAT,
    $1:minutes_zone_2::FLOAT,
    $1:minutes_zone_3::FLOAT,
    $1:any_zone_missing::BOOLEAN,
    $1:total_minutes::FLOAT,
    $1:source_file::STRING
  FROM @PMDATA_STAGE/zone_minutes/
)
FILE_FORMAT = (FORMAT_NAME = PARQUET_FORMAT);
